<script>
  import { onMount, tick } from 'svelte';
  import { get, post, put, del, attempt, toast, followTask, confirmDialog, promptDialog, formatBytes } from '../../lib/api.svelte.js';
  import { uploadForImport } from '../../lib/upload.js';
  import Modal from '../../lib/Modal.svelte';
  import ColumnFields from './ColumnFields.svelte';
  import { columnToForm, formToColumn, newColumn, defaultLabel } from './schema.js';

  // base is the database's API path; inst and db name it. onchanged lets the parent refresh
  // its table list after a rename or drop.
  let { base, db, table, initialSearch = '', readonly = false, onback, onchanged } = $props();

  let name = $state(table);
  let tab = $state('browse');
  const path = $derived(`${base}/tables/${encodeURIComponent(name)}`);

  // Browse
  let rows = $state(null);
  let page = $state({ offset: 0, limit: 50, order: '', dir: 'asc' });
  let search = $state(initialSearch);
  let searchColumn = $state('');
  let applied = $state({ term: initialSearch, column: '' });
  let cell = $state(null); // the cell being edited in place
  let rowEdit = $state(null);
  let cellInput = $state();
  let cancelled = false;

  // Structure
  let info = $state(null);
  let columnForm = $state(null);
  let indexForm = $state(null);
  let csvInput = $state();
  let csvMode = $state('insert');

  const pk = $derived(rows ? rows.schema.filter((c) => c.key === 'PRI').map((c) => c.name) : []);
  const editable = $derived(!readonly && pk.length > 0);

  const searchParams = () => {
    const q = new URLSearchParams();
    if (applied.term) q.set('search', applied.term);
    if (applied.column) q.set('column', applied.column);
    return q;
  };

  async function loadRows() {
    const q = searchParams();
    q.set('offset', page.offset);
    q.set('limit', page.limit);
    q.set('order', page.order);
    q.set('dir', page.dir);
    try {
      rows = await get(`${path}/rows?${q}`);
    } catch (e) {
      toast(e.message, true);
    }
  }

  async function loadStructure() {
    const res = await attempt(() => get(`${path}/structure`));
    if (res) info = res;
  }

  function setTab(next) {
    tab = next;
    if (next === 'structure') loadStructure();
    if (next === 'browse') loadRows();
  }

  onMount(loadRows);

  function runSearch(e) {
    e?.preventDefault();
    applied = { term: search.trim(), column: searchColumn };
    page = { ...page, offset: 0 };
    loadRows();
  }

  function clearSearch() {
    search = '';
    searchColumn = '';
    runSearch();
  }

  function sort(column) {
    page = { ...page, offset: 0, order: column, dir: page.order === column && page.dir === 'asc' ? 'desc' : 'asc' };
    loadRows();
  }

  function pageBy(delta) {
    page = { ...page, offset: Math.max(0, page.offset + delta * page.limit) };
    loadRows();
  }

  const rowObject = (row) => Object.fromEntries(rows.columns.map((c, i) => [c, row[i]]));
  const rowKey = (row) => {
    const values = rowObject(row);
    return Object.fromEntries(pk.map((k) => [k, values[k]]));
  };
  const isBinary = (v) => typeof v === 'string' && /^\[binary \d+ bytes\]$/.test(v);
  const clip = (v) => (v === null ? 'NULL' : v.length > 120 ? v.slice(0, 120) + '…' : v);
  const isGenerated = (name) => /GENERATED/i.test(rows?.schema?.find((c) => c.name === name)?.extra || '');

  // Editing in place: double-click a cell. Enter or clicking away saves, Esc cancels.

  async function startCell(rowIndex, colIndex) {
    const value = rows.rows[rowIndex][colIndex];
    if (readonly) return;
    if (!pk.length) {
      toast("This table has no primary key, so its rows can't be edited safely. Use the SQL console.", true);
      return;
    }
    if (isBinary(value)) {
      toast("Binary values can't be edited here.", true);
      return;
    }
    if (isGenerated(rows.columns[colIndex])) {
      toast('This column is generated by the database.', true);
      return;
    }
    cancelled = false;
    cell = { rowIndex, colIndex, value: value ?? '', isNull: value === null, original: value, multiline: (value ?? '').length > 60 || (value ?? '').includes('\n'), saving: false };
    await tick();
    cellInput?.focus();
    cellInput?.select?.();
  }

  async function saveCell() {
    if (!cell || cell.saving || cancelled) return;
    const next = cell.isNull ? null : cell.value;
    if (next === cell.original) {
      cell = null;
      return;
    }
    cell.saving = true;
    const { rowIndex, colIndex } = cell;
    const column = rows.columns[colIndex];
    try {
      await put(`${path}/rows`, { key: rowKey(rows.rows[rowIndex]), values: { [column]: next } });
      rows.rows[rowIndex][colIndex] = next;
      cell = null;
    } catch (e) {
      toast(e.message, true);
      if (cell) cell.saving = false;
      await tick();
      cellInput?.focus();
    }
  }

  function cellKey(e) {
    if (e.key === 'Escape') {
      e.stopPropagation();
      cancelled = true;
      cell = null;
    } else if (e.key === 'Enter' && (!cell.multiline || e.metaKey || e.ctrlKey)) {
      e.preventDefault();
      saveCell();
    }
  }

  function editRow(row) {
    const values = rowObject(row);
    rowEdit = {
      mode: 'edit',
      key: rowKey(row),
      fields: rows.schema.map((c) => ({ ...c, value: values[c.name] ?? '', isNull: values[c.name] === null, original: values[c.name], binary: isBinary(values[c.name]), generated: /GENERATED/i.test(c.extra) })),
      error: '',
    };
  }

  function newRow() {
    rowEdit = {
      mode: 'insert',
      key: {},
      fields: rows.schema.map((c) => ({
        ...c,
        value: c.defaultKind === 'value' ? c.defaultValue : '',
        isNull: c.defaultKind === 'null',
        useDefault: c.defaultKind === 'current_timestamp',
        original: undefined,
        binary: false,
        auto: /auto_increment/i.test(c.extra),
        generated: /GENERATED/i.test(c.extra),
      })),
      error: '',
    };
  }

  async function saveRow() {
    rowEdit.error = '';
    const values = {};
    for (const f of rowEdit.fields) {
      if (f.binary || f.generated) continue;
      if (rowEdit.mode === 'insert' && ((f.auto && f.value === '') || (f.useDefault && f.value === ''))) continue;
      const next = f.isNull ? null : f.value;
      if (rowEdit.mode === 'edit' && next === f.original) continue;
      values[f.name] = next;
    }
    try {
      if (rowEdit.mode === 'edit') {
        if (Object.keys(values).length) await put(`${path}/rows`, { key: rowEdit.key, values });
      } else {
        await post(`${path}/rows`, { values });
      }
      toast('Saved');
      rowEdit = null;
      loadRows();
    } catch (e) {
      rowEdit.error = e.message;
    }
  }

  async function deleteRow(row) {
    const key = rowKey(row);
    const ok = await confirmDialog({ title: 'Delete this row?', message: JSON.stringify(key), action: 'Delete', danger: true });
    if (ok && (await attempt(() => post(`${path}/rows/delete`, { key }), 'Row deleted'))) loadRows();
  }

  // Structure changes: the server builds the statement, and it's shown before running.

  async function applyAlter(body, title, danger = false) {
    const preview = await post(`${path}/alter`, { ...body, dry: true });
    const ok = await confirmDialog({ title, message: preview.sql, action: 'Run', danger, mono: true });
    if (!ok) return false;
    await post(`${path}/alter`, body);
    return true;
  }

  function startAddColumn() {
    columnForm = { mode: 'add', original: '', after: '', column: newColumn(), error: '' };
  }

  function startEditColumn(c) {
    columnForm = { mode: 'edit', original: c.name, after: '', column: columnToForm(c), error: '' };
  }

  async function saveColumn() {
    const f = columnForm;
    f.error = '';
    const column = formToColumn(f.column);
    try {
      const body = f.mode === 'add'
        ? { op: 'addColumn', column, after: f.after }
        : { op: 'modifyColumn', name: f.original, column, after: f.after };
      if (await applyAlter(body, f.mode === 'add' ? 'Add this column?' : `Change ${f.original}?`)) {
        toast('Structure updated');
        columnForm = null;
        loadStructure();
      }
    } catch (e) {
      f.error = e.message;
    }
  }

  async function dropColumn(c) {
    const ok = await attempt(() => applyAlter({ op: 'dropColumn', name: c.name }, `Drop column ${c.name}? Its data is deleted permanently.`, true));
    if (ok) {
      toast('Column dropped');
      loadStructure();
    }
  }

  async function saveIndex() {
    const f = indexForm;
    f.error = '';
    const columns = info.columns.map((c) => c.name).filter((n) => f.columns[n]);
    try {
      if (await applyAlter({ op: 'addIndex', kind: f.kind, name: f.name.trim(), columns }, 'Add this index?')) {
        indexForm = null;
        loadStructure();
      }
    } catch (e) {
      f.error = e.message;
    }
  }

  async function dropIndex(ix) {
    const ok = await attempt(() => applyAlter({ op: 'dropIndex', name: ix.name }, `Drop index ${ix.name}?`, true));
    if (ok) loadStructure();
  }

  async function rename() {
    const to = await promptDialog({ title: `Rename ${name}`, value: name, action: 'Rename' });
    if (!to || to === name) return;
    const done = await attempt(() => applyAlter({ op: 'rename', to }, 'Rename this table?'));
    if (done) {
      name = to;
      onchanged?.();
      loadStructure();
    }
  }

  async function truncate() {
    const ok = await confirmDialog({ title: `Empty ${name}?`, message: 'Every row is deleted permanently. The table itself stays.', action: 'Empty', danger: true, typed: name });
    if (ok && (await attempt(() => post(`${path}/truncate?confirm=${encodeURIComponent(name)}`), 'Table emptied'))) {
      loadStructure();
      onchanged?.();
    }
  }

  async function drop() {
    const ok = await confirmDialog({ title: `Drop ${name}?`, message: 'The table and all its rows are deleted permanently.', action: 'Drop', danger: true, typed: name });
    if (ok && (await attempt(() => del(`${path}?confirm=${encodeURIComponent(name)}`), 'Table dropped'))) {
      onchanged?.();
      onback();
    }
  }

  // Import and export of this table

  const sqlExport = (content) => `/api${base}/export?tables=${encodeURIComponent(name)}&content=${content}`;
  const csvExport = () => `/api${path}/export.csv?${searchParams()}`;

  let importing = $state(null);

  async function importCSV(e) {
    const file = e.target.files[0];
    e.target.value = '';
    if (!file) return;
    const ok = await confirmDialog({
      title: `Import ${file.name} into ${name}?`,
      message: `${formatBytes(file.size)}. The first row must name the columns. Values of \\N become NULL. A row that fails stops the import, and InnoDB tables are left unchanged.`,
      action: 'Import',
    });
    if (!ok) return;
    try {
      importing = { name: file.name, done: 0, total: file.size };
      const remote = await uploadForImport(file, (done) => (importing.done = done));
      importing = null;
      const res = await post(`${path}/import-csv`, { path: remote, mode: csvMode });
      followTask(res.task, () => {
        loadRows();
        onchanged?.();
      });
    } catch (err) {
      importing = null;
      toast(err.message, true);
    }
  }
</script>

<div class="card">
  <div class="card-head">
    <div class="row">
      <button onclick={onback} aria-label="Back to tables">←</button>
      <h2>{name}</h2>
      {#if readonly}<span class="badge">system, read only</span>{/if}
    </div>
    <div class="tabs" style="border:none">
      <button class:on={tab === 'browse'} onclick={() => setTab('browse')}>Browse</button>
      <button class:on={tab === 'structure'} onclick={() => setTab('structure')}>Structure</button>
      <button class:on={tab === 'transfer'} onclick={() => setTab('transfer')}>Import / export</button>
    </div>
  </div>

  {#if tab === 'browse'}
    <form class="row small" style="padding:10px 14px;border-bottom:1px solid var(--border)" onsubmit={runSearch}>
      <input type="search" placeholder="Search this table" bind:value={search} aria-label="Search this table" style="width:240px" />
      <select bind:value={searchColumn} aria-label="Column to search">
        <option value="">All columns</option>
        {#each rows?.columns ?? [] as c}<option value={c}>{c}</option>{/each}
      </select>
      <button type="submit">Search</button>
      {#if applied.term}<button type="button" class="link small" onclick={clearSearch}>Clear</button>{/if}
      <span class="grow"></span>
      {#if rows}
        <span class="muted">{rows.total ? page.offset + 1 : 0}–{Math.min(page.offset + page.limit, rows.total)} of {rows.total}{applied.term ? ' matching' : ''}</span>
        <select aria-label="Rows per page" value={page.limit} onchange={(e) => { page = { ...page, offset: 0, limit: Number(e.target.value) }; loadRows(); }}>
          {#each [25, 50, 100, 500] as n}<option value={n}>{n} per page</option>{/each}
        </select>
        <button type="button" disabled={page.offset === 0} onclick={() => pageBy(-1)}>Previous</button>
        <button type="button" disabled={page.offset + page.limit >= rows.total} onclick={() => pageBy(1)}>Next</button>
        {#if !readonly}<button type="button" class="primary" onclick={newRow}>Add row</button>{/if}
      {/if}
    </form>

    {#if rows}
      {#if !readonly && !pk.length}<div class="notice" style="margin:12px">▲ This table has no primary key, so rows can't be edited here. Use the SQL console, or add a key under Structure.</div>{/if}
      {#if editable}<div class="hint" style="padding:8px 14px 0">Double-click a value to edit it. Enter saves, Esc cancels.</div>{/if}
      <div class="table-wrap">
        <table class="grid">
          <thead>
            <tr>
              {#each rows.columns as c}
                <th><button class="link" onclick={() => sort(c)}>{c}{page.order === c ? (page.dir === 'asc' ? ' ↑' : ' ↓') : ''}</button></th>
              {/each}
              {#if editable}<th></th>{/if}
            </tr>
          </thead>
          <tbody>
            {#each rows.rows as row, r}
              <tr>
                {#each row as v, c}
                  {#if cell && cell.rowIndex === r && cell.colIndex === c}
                    <td class="editing">
                      {#if cell.multiline}
                        <textarea bind:this={cellInput} bind:value={cell.value} disabled={cell.isNull} rows="5" onkeydown={cellKey} onblur={saveCell}></textarea>
                      {:else}
                        <input bind:this={cellInput} bind:value={cell.value} disabled={cell.isNull} onkeydown={cellKey} onblur={saveCell} />
                      {/if}
                      {#if rows.schema[c]?.nullable}
                        <label class="row hint"><input type="checkbox" bind:checked={cell.isNull} onmousedown={(e) => e.preventDefault()} /> NULL</label>
                      {/if}
                      {#if cell.multiline}<div class="hint">⌘/Ctrl+Enter saves</div>{/if}
                    </td>
                  {:else}
                    <td class="small value" class:muted={v === null || isBinary(v)} title={v ?? 'NULL'} ondblclick={() => startCell(r, c)}>{clip(v)}</td>
                  {/if}
                {/each}
                {#if editable}
                  <td class="actions">
                    <button onclick={() => editRow(row)}>Edit</button>
                    <button class="danger" onclick={() => deleteRow(row)}>Delete</button>
                  </td>
                {/if}
              </tr>
            {:else}
              <tr><td colspan={rows.columns.length + 1} class="empty">{applied.term ? 'No rows match.' : 'This table is empty.'}</td></tr>
            {/each}
          </tbody>
        </table>
      </div>
    {/if}
  {:else if tab === 'structure'}
    {#if info}
      <div class="spread" style="padding:12px 14px">
        <div class="small muted">
          {info.engine || info.type} · {info.collation || 'no collation'} · about {info.rows} rows · {formatBytes(info.size)}{info.comment ? ` · ${info.comment}` : ''}
        </div>
        {#if !readonly}
          <div class="row">
            <button onclick={rename}>Rename</button>
            <button class="danger" onclick={truncate}>Empty</button>
            <button class="danger" onclick={drop}>Drop</button>
            <button class="primary" onclick={startAddColumn}>Add column</button>
          </div>
        {/if}
      </div>
      <div class="table-wrap">
        <table>
          <thead><tr><th>Column</th><th>Type</th><th>Null</th><th>Key</th><th>Default</th><th>Extra</th><th>Comment</th><th></th></tr></thead>
          <tbody>
            {#each info.columns as c (c.name)}
              <tr>
                <td class="mono">{c.name}</td>
                <td class="mono muted break">{c.type}</td>
                <td class="small">{c.nullable ? 'Yes' : 'No'}</td>
                <td>{#if c.key}<span class="badge">{{ PRI: 'primary', UNI: 'unique', MUL: 'index' }[c.key] ?? c.key}</span>{/if}</td>
                <td class="mono small muted break">{defaultLabel(c)}</td>
                <td class="small muted">{c.extra}</td>
                <td class="small muted break">{c.comment}</td>
                <td class="actions">
                  {#if !readonly}
                    <button onclick={() => startEditColumn(c)}>Edit</button>
                    <button class="danger" onclick={() => dropColumn(c)}>Drop</button>
                  {/if}
                </td>
              </tr>
            {/each}
          </tbody>
        </table>
      </div>

      <div class="spread" style="padding:16px 14px 8px;border-top:1px solid var(--border);margin-top:8px">
        <h2>Indexes</h2>
        {#if !readonly}
          <button onclick={() => (indexForm = { kind: 'index', name: '', columns: {}, error: '' })}>Add index</button>
        {/if}
      </div>
      <div class="table-wrap">
        <table>
          <thead><tr><th>Name</th><th>Kind</th><th>Columns</th><th></th></tr></thead>
          <tbody>
            {#each info.indexes as ix (ix.name)}
              <tr>
                <td class="mono">{ix.name}</td>
                <td class="small">{ix.name === 'PRIMARY' ? 'Primary' : ix.kind === 'FULLTEXT' ? 'Fulltext' : ix.unique ? 'Unique' : 'Index'}</td>
                <td class="mono small muted">{ix.columns.join(', ')}</td>
                <td class="actions">{#if !readonly}<button class="danger" onclick={() => dropIndex(ix)}>Drop</button>{/if}</td>
              </tr>
            {:else}
              <tr><td colspan="4" class="empty">No indexes.</td></tr>
            {/each}
          </tbody>
        </table>
      </div>

      {#if info.create}
        <details class="small" style="padding:12px 14px">
          <summary style="cursor:pointer" class="muted">Show CREATE TABLE</summary>
          <pre class="log" style="margin-top:8px">{info.create}</pre>
        </details>
      {/if}
    {/if}
  {:else}
    <div class="card-pad form" style="max-width:640px">
      <h2>Export this table</h2>
      <div class="row">
        <a class="btn" href={sqlExport('full')}>SQL: structure and data</a>
        <a class="btn" href={sqlExport('structure')}>SQL: structure only</a>
        <a class="btn" href={sqlExport('data')}>SQL: data only</a>
        <a class="btn" href={csvExport()}>CSV{applied.term ? ' (search results)' : ''}</a>
      </div>
      {#if !readonly}
        <h2 style="margin-top:12px">Import a CSV</h2>
        <label class="field">If a row's key already exists
          <select bind:value={csvMode}>
            <option value="insert">Stop with an error</option>
            <option value="ignore">Skip that row</option>
            <option value="replace">Replace the existing row</option>
          </select>
        </label>
        <div class="hint">The first row must name the columns. To import SQL, use the database's Import / export tab.</div>
        <div>
          <button class="primary" disabled={!!importing} onclick={() => csvInput.click()}>
            {importing ? `Uploading ${formatBytes(importing.done)} of ${formatBytes(importing.total)}` : 'Choose CSV file'}
          </button>
          <input bind:this={csvInput} type="file" accept=".csv,text/csv" hidden onchange={importCSV} />
        </div>
      {/if}
    </div>
  {/if}
</div>

{#if rowEdit}
  <Modal title={rowEdit.mode === 'edit' ? 'Edit row' : 'Add row'} onclose={() => (rowEdit = null)}>
    <form class="form" id="row-form" onsubmit={(e) => { e.preventDefault(); saveRow(); }}>
      {#each rowEdit.fields as f}
        <label class="field">
          <span class="row">{f.name} <span class="hint mono">{f.type}</span>{#if f.key === 'PRI'}<span class="badge">key</span>{/if}</span>
          {#if f.binary || f.generated}
            <input value={f.generated ? 'Generated by the database' : f.value} disabled />
          {:else if String(f.value).length > 80 || /text|json/i.test(f.type)}
            <textarea rows="4" bind:value={f.value} disabled={f.isNull}></textarea>
          {:else}
            <input bind:value={f.value} disabled={f.isNull} placeholder={f.auto ? 'Automatic' : f.useDefault ? 'Current time' : ''} />
          {/if}
          {#if f.nullable && !f.binary && !f.generated}<span class="row hint"><input type="checkbox" bind:checked={f.isNull} /> NULL</span>{/if}
        </label>
      {/each}
      {#if rowEdit.error}<div class="error">{rowEdit.error}</div>{/if}
    </form>
    {#snippet foot()}
      <button onclick={() => (rowEdit = null)}>Cancel</button>
      <button class="primary" type="submit" form="row-form">Save</button>
    {/snippet}
  </Modal>
{/if}

{#if columnForm}
  <Modal title={columnForm.mode === 'add' ? 'Add column' : `Edit column ${columnForm.original}`} onclose={() => (columnForm = null)}>
    <form class="form" id="column-form" onsubmit={(e) => { e.preventDefault(); saveColumn(); }}>
      <ColumnFields bind:column={columnForm.column} />
      <label class="field">Position
        <select bind:value={columnForm.after}>
          <option value="">{columnForm.mode === 'add' ? 'At the end' : 'Keep where it is'}</option>
          <option value="^">First</option>
          {#each info.columns.filter((c) => c.name !== columnForm.original) as c}<option value={c.name}>After {c.name}</option>{/each}
        </select>
      </label>
      {#if columnForm.error}<div class="error">{columnForm.error}</div>{/if}
    </form>
    {#snippet foot()}
      <button onclick={() => (columnForm = null)}>Cancel</button>
      <button class="primary" type="submit" form="column-form">Review change</button>
    {/snippet}
  </Modal>
{/if}

{#if indexForm}
  <Modal title="Add index" onclose={() => (indexForm = null)}>
    <form class="form" id="index-form" onsubmit={(e) => { e.preventDefault(); saveIndex(); }}>
      <div class="form-grid">
        <label class="field">Kind
          <select bind:value={indexForm.kind}>
            <option value="index">Index</option>
            <option value="unique">Unique</option>
            <option value="fulltext">Fulltext</option>
            <option value="primary">Primary key</option>
          </select>
        </label>
        {#if indexForm.kind !== 'primary'}
          <label class="field">Name (optional) <input class="mono" bind:value={indexForm.name} /></label>
        {/if}
      </div>
      <div class="field small">Columns
        <div class="stack" style="gap:4px;margin-top:6px">
          {#each info.columns as c (c.name)}
            <label class="row"><input type="checkbox" bind:checked={indexForm.columns[c.name]} /> <span class="mono">{c.name}</span> <span class="hint mono">{c.type}</span></label>
          {/each}
        </div>
      </div>
      {#if indexForm.error}<div class="error">{indexForm.error}</div>{/if}
    </form>
    {#snippet foot()}
      <button onclick={() => (indexForm = null)}>Cancel</button>
      <button class="primary" type="submit" form="index-form">Review change</button>
    {/snippet}
  </Modal>
{/if}
